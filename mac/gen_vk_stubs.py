#!/usr/bin/env python3
"""Generates platform/vk_stub_list.inc: the MoltenVK entry points that ReShade hooks (plus the loader 'terminator'
functions), as an X-macro list. Re-run when ReShade or MoltenVK is updated:  gen_vk_stubs.py <libMoltenVK.dylib>"""
import re, subprocess, sys
mvk = sys.argv[1] if len(sys.argv) > 1 else '/opt/homebrew/lib/libMoltenVK.dylib'
src = open('../reshade/source/vulkan/vulkan.cpp').read()
src = src[:src.index('// macOS: look up ReShade')] if '// macOS: look up ReShade' in src else src
hooked = set('vk' + n for n in re.findall(r'RESHADE_VULKAN_HOOK_PROC\((\w+)\)', src) if n != 'name')
hooked |= set('vk' + n + s for n, s in re.findall(r'RESHADE_VULKAN_HOOK_PROC_OPTIONAL\((\w+),\s*(\w*)\)', src) if n != 'name')
extra = {'vkCreateInstance', 'vkCreateDevice', 'vkGetInstanceProcAddr', 'vkGetDeviceProcAddr', 'vkEnumeratePhysicalDevices', 'vkEnumeratePhysicalDeviceGroups',
         'vkEnumeratePhysicalDeviceGroupsKHR', 'vkGetDeviceQueue', 'vkGetDeviceQueue2', 'vkAllocateCommandBuffers'}
exports = set(l.split()[-1][1:] for l in subprocess.run(['nm', '-gU', mvk], capture_output=True, text=True).stdout.splitlines() if l.split()[-1].startswith('_vk'))
names = sorted((hooked | extra) & exports)
missing = sorted((hooked | extra) - exports)
with open('platform/vk_stub_list.inc', 'w') as f:
    f.write('// generated by gen_vk_stubs.py\n#define RSX_FUNCTIONS(X) \\\n' + ' \\\n'.join('\tX(%s)' % n for n in names) + '\n')
print(len(names), 'stubs;', len(missing), 'hooked names not exported by MoltenVK (ignored)')
