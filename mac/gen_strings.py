#!/usr/bin/env python3
"""Generates platform/localization_data.inc from reshade/res/lang_*.rc2 (STRINGTABLE entries: <id> "<text>")."""
import glob, os, re, sys
res = sys.argv[1] if len(sys.argv) > 1 else '../reshade/res'
out = ['// generated by gen_strings.py', 'struct LocalizedString { const char *language; unsigned short id; const char *text; };', 'static const LocalizedString kStrings[] = {']
def decode(s):
    r = []; i = 0
    while i < len(s):
        c = s[i]
        if c == '"' and s[i:i+2] == '""': r.append('"'); i += 2
        elif c == '\\' and i + 1 < len(s):
            n = s[i+1]
            r.append({'n': '\n', 't': '\t', 'r': '\r', '\\': '\\', '"': '"'}.get(n, '\\' + n)); i += 2
        else: r.append(c); i += 1
    return ''.join(r)
def c_literal(s):
    return '"' + ''.join('\\x%02x' % b for b in s.encode('utf-8')) + '"'
langs = []
for f in sorted(glob.glob(res + '/lang_*.rc2')):
    lang = os.path.basename(f)[5:-4]; langs.append(lang)
    for line in open(f, encoding='utf-8'):
        m = re.match(r'^\s*(\d+)\s+"(.*)"\s*$', line.rstrip('\n'))
        if m: out.append('\t{ "%s", %s, %s },' % (lang, m.group(1), c_literal(decode(m.group(2)))))
out.append('};')
open('platform/localization_data.inc', 'w').write('\n'.join(out) + '\n')
print(len(langs), 'languages:', ' '.join(langs))
