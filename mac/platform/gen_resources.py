#!/usr/bin/env python3
"""Generates embedded_resources.inc from res/resource.h + res/resource.rc (RCDATA entries that exist on disk)."""
import re, sys, os
res = sys.argv[1]; out = sys.argv[2]
ids = dict((n, int(v)) for n, v in re.findall(r'#define\s+(IDR_\w+|IDB_\w+)\s+(\d+)', open(res + '/resource.h').read()))
entries = re.findall(r'^(\w+)\s+RCDATA\s+"([^"]+)"', open(res + '/resource.rc').read(), re.M)
lines = ['// generated by gen_resources.py', '#include <cstddef>', 'struct embedded_res { unsigned short id; const unsigned char *data; size_t size; };']
table = []
for name, path in entries:
    f = os.path.normpath(os.path.join(res, path.replace('\\\\', '/').replace('\\', '/')))
    if name not in ids or not os.path.exists(f): continue
    data = open(f, 'rb').read()
    lines.append('static const unsigned char res_%s[] = {%s};' % (name, ','.join(map(str, data)) if data else '0'))
    table.append('{%d, res_%s, %d},' % (ids[name], name, len(data)))
lines.append('static const embedded_res kEmbedded[] = {' + ''.join(table) + '};')
open(out, 'w').write('\n'.join(lines) + '\n')
print(len(table), 'resources embedded')
